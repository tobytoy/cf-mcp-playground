/**
 * 站名別名正規化表 (繁簡/異體字與俗稱對照)
 */
export const STATION_ALIAS_MAP: Record<string, string> = {
  "台北": "臺北",
  "台中": "臺中",
  "台南": "臺南",
  "台東": "臺東",
  "台北車站": "臺北",
  "台中車站": "臺中",
  "台南車站": "臺南",
  "高雄": "左營", // 高鐵高雄站為左營
  "高雄車站": "高雄",
  "左營/高雄": "左營",
  "左營車站": "左營"
};

/**
 * 清理站名字串 (移除「站」、「車站」、空白等)
 */
export function normalizeStationInput(input: string): string {
  if (!input) return "";
  let s = input.trim().replace(/(車站|火車站|高鐵站|站)$/, "");
  return s;
}

/**
 * 尋找高鐵站點
 */
export function resolveTHSRStation(input: string): StationItem | undefined {
  const clean = normalizeStationInput(input);
  // 直接匹配
  const exact = THSR_STATIONS.find(s => s.nameZh === clean || s.nameEn.toLowerCase() === clean.toLowerCase() || s.id === clean);
  if (exact) return exact;

  // 別名匹配 (如 高雄 -> 左營)
  if (clean === "高雄") {
    return THSR_STATIONS.find(s => s.nameZh === "左營");
  }
  const alias = STATION_ALIAS_MAP[clean];
  if (alias) {
    const aliasMatch = THSR_STATIONS.find(s => s.nameZh === alias || s.nameZh === clean);
    if (aliasMatch) return aliasMatch;
  }

  // 模糊匹配
  return THSR_STATIONS.find(s => clean.includes(s.nameZh) || s.nameZh.includes(clean));
}

/**
 * 尋找台鐵站點
 */
export function resolveTRAStation(input: string): StationItem | undefined {
  const clean = normalizeStationInput(input);
  // 直接匹配 (ID 或 名稱)
  let found = TRA_STATIONS.find(s => s.nameZh === clean || s.id === clean || s.nameEn.toLowerCase() === clean.toLowerCase());
  if (found) return found;

  // 轉換 台 <-> 臺
  const withTai = clean.replace(/台/g, "臺");
  found = TRA_STATIONS.find(s => s.nameZh === withTai);
  if (found) return found;

  const withPlainTai = clean.replace(/臺/g, "台");
  found = TRA_STATIONS.find(s => s.nameZh === withPlainTai);
  if (found) return found;

  // 模糊包含
  return TRA_STATIONS.find(s => clean.includes(s.nameZh) || s.nameZh.includes(clean));
}

